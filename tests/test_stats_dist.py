def test_silverman_bandwidth():
    assert D.silverman_bandwidth([1, 2, 3, 4, 5]) == pytest.approx(1.2136, abs=1e-4)
    for name, w in PIN_VIOLIN.items():
        assert _close(D.silverman_bandwidth(PIN_LISTS[name]), w["bandwidth"]), name
    assert D.silverman_bandwidth([4, 4, 4]) == 0 and D.silverman_bandwidth([9]) == 0 and D.silverman_bandwidth([]) == 0
    # the span/100 floor engages when the IQR collapses (Silverman alone would give 0)
    k = [0] * 9 + [10]
    assert D.box_stats(k).q1 == D.box_stats(k).q3 == 0
    assert D.silverman_bandwidth(k) == pytest.approx(0.1)
    # ...and does not for [0,0,0,0,10] (the plan text expected it to; Plotly's value is 1.4224)
    assert D.silverman_bandwidth([0, 0, 0, 0, 10]) == pytest.approx(1.4224271012503327, rel=1e-12)


def test_violin_shape_geometry():
    vals = [1, 2, 3, 4, 5]
    v = D.violin_shape(vals)
    bw = 1.2135899283964375
    assert v.bandwidth == pytest.approx(bw, rel=1e-12)
    assert v.ts[0] == pytest.approx(1 - 2 * bw, rel=1e-12)
    assert v.ts[-1] == pytest.approx(5 + 2 * bw, rel=1e-12)
    assert max(v.half_widths) == 0.35
    dist = v.ts[-1] - v.ts[0]
    assert len(v.ts) == math.ceil(dist / (bw / 3)) + 1 == 23
    peak = v.ts[v.half_widths.index(max(v.half_widths))]
    assert abs(peak - 3) < dist / 22
    n = len(v.half_widths)
    for i in range(n):
        assert v.half_widths[i] == pytest.approx(v.half_widths[n - 1 - i], abs=1e-12)    # symmetric sample
    assert min(v.half_widths) > 0
    other = D.violin_shape(vals, half_width=0.5)
    assert max(other.half_widths) == 0.5


