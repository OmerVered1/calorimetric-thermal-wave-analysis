def test_violin_density_matches_plotly_makekde():
    for name, w in PIN_VIOLIN.items():
        vals = PIN_LISTS[name]
        s = D.violin_shape(vals)
        dens = w["density"]
        if w["bandwidth"] == 0:        # Plotly: one density point; the plan's degenerate shape is [v, v] / [0, 0]
            assert len(dens) == 1 and s.ts == [dens[0]["t"]] * 2 and s.half_widths == [0, 0]
            continue
        assert len(s.ts) == w["n"] == len(dens), name
        top = max(d["v"] for d in dens)
        for t, hw, d in zip(s.ts, s.half_widths, dens):
            assert t == pytest.approx(d["t"], rel=1e-12, abs=1e-12), name
            assert hw == pytest.approx(d["v"] / top * 0.35, rel=1e-9, abs=1e-12), name
    seven = PIN_LISTS["g"]
    assert len(seven) == 7
    s = D.violin_shape(seven)
    assert s.bandwidth == pytest.approx(PIN_VIOLIN["g"]["bandwidth"], rel=1e-12)


def test_jitter_x():
    for index in (0, 1, 4):
        xs = D.jitter_x(index, 50)
        assert len(xs) == 50
        lo, hi = index - 0.525 - 0.105, index - 0.525 + 0.105
        assert all(lo <= x <= hi for x in xs)
        assert xs == D.jitter_x(index, 50)
        assert xs[:10] == D.jitter_x(index, 10)         # a prefix of the same stream: stable when n changes
    assert D.jitter_x(0, 5) != D.jitter_x(1, 5)
    assert len(set(D.jitter_x(2, 20))) > 1
    assert D.jitter_x(3, 0) == []
